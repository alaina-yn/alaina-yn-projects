const assert=require('node:assert/strict');
const {audit,vendor,ai}=require('../assets/logic.js');
let all={a1:'current',a2:'current',a3:'current',a4:'current',a5:'current'};
assert.equal(audit(all).score,5);
assert.equal(audit(all).tier,'Evidence coverage complete');
assert.equal(audit({...all,a4:'missing'}).tier,'Not ready');
assert.equal(audit({...all,a4:'stale'}).tier,'Conditional');
assert.throws(()=>audit({...all,a1:'invalid'}));
const v={criticality:'3',data:'3',ai:'2',subprocessors:'1',security:'verified',privacy:'verified'};
assert.equal(vendor(v).score,9);
assert.equal(vendor(v).tier,'High');
assert.match(vendor({...v,security:'pending'}).decision,/Defer/);
assert.throws(()=>vendor({...v,criticality:'99'}));
const a={impact:'3',autonomy:'3',sensitivity:'3',owner:'yes',evaluation:'yes'};
assert.equal(ai(a).score,9);
assert.equal(ai(a).tier,'Elevated');
assert.match(ai({...a,owner:'no'}).decision,/Defer/);
assert.match(ai({...a,evaluation:'no'}).decision,/Defer/);
assert.throws(()=>ai({...a,owner:'maybe'}));
console.log('14 assertions passed: audit, vendor, AI triage, blockers and invalid input');
